//! The original's skin pictures, so the interface can be drawn with the same art as the original client.
//!
//! A skin folder (the game's `cd_image/gui/Default`, or a user skin under `.../Funcom/Anarchy Online/<hash>/Anarchy
//! Online/Gui/<Name>` such as the AOU mod's) holds `Graphics.uvgi`, a text index of `NAME offset length` lines, and
//! `Graphics.uvga`, the sprites themselves: each entry is a whole PNG at that offset, and pure green `(0, 255, 0)` in it
//! is the transparent key. A user skin ships only the sprites it changes (the AOU skins have 287 of the 789), so the
//! skin is a stack of layers searched in order: the `gui_dir` setting (or `MAO_GUI_DIR`), the folder of the `theme`
//! setting, then the game's own Default, which has everything. A sprite is decoded and uploaded the first time it is
//! asked for and kept.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

/// One skin folder's index and atlas.
pub struct Layer {
    pub dir: PathBuf,
    index: HashMap<String, (usize, usize)>,
    atlas: Vec<u8>,
}

/// The `NAME offset length` lines of an index; a title line (`GUIGFX.UVGI 1.0 Generated by ...`) and the count line
/// are skipped by not being three fields with two numbers (the game's own index has no title line).
pub fn parse_index(text: &str) -> Vec<(String, usize, usize)> {
    text.lines()
        .filter_map(|line| {
            let mut parts = line.split_whitespace();
            let (name, offset, length) = (parts.next()?, parts.next()?.parse().ok()?, parts.next()?.parse().ok()?);
            parts.next().is_none().then(|| (name.to_string(), offset, length))
        })
        .collect()
}

/// A file of the folder by either spelling of its name (`Graphics.uvga` in the game, `Graphics.UVGA` in the skins).
fn read_either(dir: &Path, lower: &str, upper: &str) -> Option<Vec<u8>> {
    std::fs::read(dir.join(lower)).or_else(|_| std::fs::read(dir.join(upper))).ok()
}

impl Layer {
    pub fn open(dir: &Path) -> Option<Layer> {
        let index = String::from_utf8_lossy(&read_either(dir, "Graphics.uvgi", "Graphics.UVGI")?).into_owned();
        let atlas = read_either(dir, "Graphics.uvga", "Graphics.UVGA")?;
        let index: HashMap<String, (usize, usize)> = parse_index(&index).into_iter().map(|(n, o, l)| (n, (o, l))).collect();
        (!index.is_empty()).then_some(Layer { dir: dir.to_path_buf(), index, atlas })
    }

    /// The PNG of a sprite.
    pub fn bytes(&self, name: &str) -> Option<&[u8]> {
        let &(offset, length) = self.index.get(name)?;
        self.atlas.get(offset..offset + length)
    }

    pub fn names(&self) -> impl Iterator<Item = &str> {
        self.index.keys().map(String::as_str)
    }
}

/// A sprite's pixels with the green key made transparent, and its size.
pub fn decode(png: &[u8]) -> Option<(Vec<u8>, [usize; 2])> {
    let image = image::load_from_memory(png).ok()?;
    let mut rgba = image.to_rgba8();
    for pixel in rgba.pixels_mut() {
        if pixel.0[..3] == [0, 255, 0] {
            pixel.0 = [0, 0, 0, 0];
        }
    }
    let size = [rgba.width() as usize, rgba.height() as usize];
    Some((rgba.into_raw(), size))
}

/// A sprite on the GPU.
#[derive(Clone)]
pub struct Sprite {
    pub texture: egui::TextureHandle,
    pub size: egui::Vec2,
}

/// The skin in use: its layers in search order and the sprites loaded so far.
pub struct Skin {
    ctx: egui::Context,
    layers: Vec<Layer>,
    cache: Mutex<HashMap<String, Option<Sprite>>>,
}

impl Skin {
    /// Opens the folders that can be opened, in the order given; None when none can.
    pub fn open(ctx: &egui::Context, dirs: &[PathBuf]) -> Option<Skin> {
        let layers: Vec<Layer> = dirs.iter().filter_map(|d| Layer::open(d)).collect();
        (!layers.is_empty()).then(|| Skin { ctx: ctx.clone(), layers, cache: Mutex::new(HashMap::new()) })
    }

    /// The folders in use, first searched first.
    pub fn dirs(&self) -> Vec<&Path> {
        self.layers.iter().map(|l| l.dir.as_path()).collect()
    }

    /// The PNG of a sprite from the first layer that has it.
    pub fn bytes(&self, name: &str) -> Option<&[u8]> {
        self.layers.iter().find_map(|l| l.bytes(name))
    }

    pub fn has(&self, name: &str) -> bool {
        self.layers.iter().any(|l| l.index.contains_key(name))
    }

    /// A sprite, uploaded on first use.
    pub fn get(&self, name: &str) -> Option<Sprite> {
        let mut cache = self.cache.lock().unwrap();
        if let Some(found) = cache.get(name) {
            return found.clone();
        }
        let sprite = self.bytes(name).and_then(decode).map(|(rgba, size)| Sprite {
            texture: self.ctx.load_texture(name, egui::ColorImage::from_rgba_unmultiplied(size, &rgba), egui::TextureOptions::LINEAR),
            size: egui::vec2(size[0] as f32, size[1] as f32),
        });
        cache.insert(name.to_string(), sprite.clone());
        sprite
    }

    /// Draws a sprite at `at` (its top left), only its lower `fraction` when that is below 1 (a bar filling up), tinted.
    pub fn draw(&self, painter: &egui::Painter, name: &str, at: egui::Pos2, fraction: f32, tint: egui::Color32) -> Option<egui::Rect> {
        let sprite = self.get(name)?;
        let shown = sprite.size.y * fraction;
        let rect = egui::Rect::from_min_size(at + egui::vec2(0.0, sprite.size.y - shown), egui::vec2(sprite.size.x, shown));
        let uv = egui::Rect::from_min_max(egui::pos2(0.0, 1.0 - fraction), egui::pos2(1.0, 1.0));
        painter.image(sprite.texture.id(), rect, uv, tint);
        Some(rect)
    }

    /// Draws a `<prefix>_LEFT`, `_MIDDLE` (stretched) and `_RIGHT` capsule over `rect`, the end pieces scaled to the rect's height;
    /// false when the pieces are missing.
    pub fn three_slice(&self, painter: &egui::Painter, prefix: &str, rect: egui::Rect, tint: egui::Color32) -> bool {
        let (Some(l), Some(m), Some(r)) = (self.get(&format!("{prefix}_LEFT")), self.get(&format!("{prefix}_MIDDLE")), self.get(&format!("{prefix}_RIGHT"))) else { return false };
        let uv = egui::Rect::from_min_max(egui::Pos2::ZERO, egui::pos2(1.0, 1.0));
        let scale = rect.height() / m.size.y.max(1.0);
        let (lw, rw) = (l.size.x * scale, r.size.x * scale);
        painter.image(l.texture.id(), egui::Rect::from_min_size(rect.min, egui::vec2(lw, rect.height())), uv, tint);
        painter.image(m.texture.id(), egui::Rect::from_min_max(egui::pos2(rect.left() + lw, rect.top()), egui::pos2(rect.right() - rw, rect.bottom())), uv, tint);
        painter.image(r.texture.id(), egui::Rect::from_min_size(egui::pos2(rect.right() - rw, rect.top()), egui::vec2(rw, rect.height())), uv, tint);
        true
    }

    /// Draws a sprite stretched over `rect`.
    pub fn draw_in(&self, painter: &egui::Painter, name: &str, rect: egui::Rect, tint: egui::Color32) -> bool {
        match self.get(name) {
            Some(sprite) => {
                painter.image(sprite.texture.id(), rect, egui::Rect::from_min_max(egui::Pos2::ZERO, egui::pos2(1.0, 1.0)), tint);
                true
            }
            None => false,
        }
    }
}

/// The folders to search for the settings: the skin folder (`gui_dir`, or `MAO_GUI_DIR`), the theme's folder, then the game's
/// own Default. A folder is listed once.
pub fn dirs(gui_dir: &str, theme: &str, aou_mod: &str) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    let user = if gui_dir.trim().is_empty() { std::env::var("MAO_GUI_DIR").unwrap_or_default() } else { gui_dir.to_string() };
    if !user.trim().is_empty() {
        out.push(PathBuf::from(user.trim()));
    }
    let forced = std::env::var("MAO_THEME").ok();
    out.extend(crate::theme::theme_dir(forced.as_deref().unwrap_or(theme), aou_mod));
    out.extend(crate::theme::game_dir().map(|g| g.join("cd_image/gui/Default")));
    let mut seen = Vec::new();
    out.retain(|d| {
        let key = d.to_string_lossy().to_lowercase().replace('\\', "/");
        let new = !seen.contains(&key);
        seen.push(key);
        new
    });
    out
}

/// Sets the folders the context's skin is read from (and drops the skin loaded before, so the next `skin` reloads it).
pub fn configure(ctx: &egui::Context, dirs: Vec<PathBuf>) {
    ctx.data_mut(|d| {
        d.insert_temp(egui::Id::new("skin-dirs"), dirs);
        d.remove::<Option<Arc<Skin>>>(egui::Id::new("skin"));
        d.remove::<Option<Arc<crate::font::BitmapFont>>>(egui::Id::new("font-chat"));
    });
}

/// The skin of this context, loaded once per configuration; None when no folder with the pictures can be found.
pub fn skin(ctx: &egui::Context) -> Option<Arc<Skin>> {
    let id = egui::Id::new("skin");
    if let Some(found) = ctx.data(|d| d.get_temp::<Option<Arc<Skin>>>(id)) {
        return found;
    }
    let dirs = ctx.data(|d| d.get_temp::<Vec<PathBuf>>(egui::Id::new("skin-dirs"))).unwrap_or_else(|| dirs("", "", ""));
    let loaded = Skin::open(ctx, &dirs).map(Arc::new);
    match &loaded {
        Some(s) => eprintln!("skin: {}", s.dirs().iter().map(|d| d.display().to_string()).collect::<Vec<_>>().join(" > ")),
        None => eprintln!("skin: no Graphics.uvga found (plain interface)"),
    }
    ctx.data_mut(|d| d.insert_temp(id, loaded.clone()));
    loaded
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_index_is_read_with_or_without_a_title_line() {
        let skin = "GUIGFX.UVGI 1.0 Generated by AO-Skintool v2.4\n287\nGFX_GUI_A 0 10\nGFX_GUI_B 10 20\n";
        assert_eq!(parse_index(skin), vec![("GFX_GUI_A".to_string(), 0, 10), ("GFX_GUI_B".to_string(), 10, 20)]);
        // the game's own index starts with the count
        assert_eq!(parse_index("790\nGFX_FONT_CHAT9 0 2729\n"), vec![("GFX_FONT_CHAT9".to_string(), 0, 2729)]);
    }

    /// A one-colour PNG.
    fn png(color: [u8; 4], w: u32, h: u32) -> Vec<u8> {
        let image = image::RgbaImage::from_pixel(w, h, image::Rgba(color));
        let mut out = std::io::Cursor::new(Vec::new());
        image::DynamicImage::ImageRgba8(image).write_to(&mut out, image::ImageFormat::Png).unwrap();
        out.into_inner()
    }

    fn write_layer(dir: &Path, entries: &[(&str, &[u8])]) {
        std::fs::create_dir_all(dir).unwrap();
        let mut atlas = Vec::new();
        let mut index = String::from("GUIGFX.UVGI 1.0 test\n");
        index += &format!("{}\n", entries.len());
        for (name, bytes) in entries {
            index += &format!("{name} {} {}\n", atlas.len(), bytes.len());
            atlas.extend_from_slice(bytes);
        }
        std::fs::write(dir.join("Graphics.UVGI"), index).unwrap();
        std::fs::write(dir.join("Graphics.UVGA"), atlas).unwrap();
    }

    #[test]
    fn layers_are_searched_in_order_and_green_is_transparent() {
        let root = std::env::temp_dir().join(format!("mao-skin-test-{}", std::process::id()));
        let (user, base) = (root.join("user"), root.join("base"));
        let red = png([255, 0, 0, 255], 2, 2);
        let blue = png([0, 0, 255, 255], 3, 1);
        let green = png([0, 255, 0, 255], 1, 1);
        write_layer(&user, &[("GFX_GUI_A", &red)]);
        write_layer(&base, &[("GFX_GUI_A", &blue), ("GFX_GUI_B", &green)]);
        let ctx = egui::Context::default();
        let skin = Skin::open(&ctx, &[user.clone(), root.join("missing"), base.clone()]).unwrap();
        assert_eq!(skin.dirs(), vec![user.as_path(), base.as_path()]);
        // the user's layer wins, the base fills in what it lacks
        assert_eq!(skin.get("GFX_GUI_A").unwrap().size, egui::vec2(2.0, 2.0));
        assert_eq!(skin.get("GFX_GUI_B").unwrap().size, egui::vec2(3.0, 1.0).min(egui::vec2(1.0, 1.0)));
        assert!(skin.get("GFX_GUI_C").is_none() && !skin.has("GFX_GUI_C"));
        let (pixels, size) = decode(skin.bytes("GFX_GUI_B").unwrap()).unwrap();
        assert_eq!((size, pixels), ([1, 1], vec![0, 0, 0, 0]));
        assert!(Skin::open(&ctx, &[root.join("nowhere")]).is_none());
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn the_folders_come_from_the_settings_in_order() {
        let d = dirs("D:/skins/Blue", "aou_cyt", "C:/mods/aou");
        assert_eq!(d[0], PathBuf::from("D:/skins/Blue"));
        assert_eq!(d[1], PathBuf::from("C:/mods/aou/Gui/AOU_CYT"));
        // the same folder named twice is listed once
        assert_eq!(dirs("C:/mods/aou/Gui/AOU_CYT", "aou_cyt", "C:/mods/aou").len(), dirs("", "aou_cyt", "C:/mods/aou").len());
    }
}
